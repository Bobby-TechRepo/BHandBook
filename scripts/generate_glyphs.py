#!/usr/bin/env python3
"""Generates app/src/main/java/com/bsoft/bhandbook/core/icons/GlyphData.kt from the Iconify "Glyphs" set (MIT, Goran Spasojevic).

    python3 scripts/generate_glyphs.py                    # downloads @iconify-json/glyphs from the npm registry itself (needs internet once)
    python3 scripts/generate_glyphs.py path/to/icons.json # or use an icons.json you already have

Single-colour <path> icons (filled and/or stroked, with group-level defaults) are accepted. Anything else (opacity, transforms, other shapes) aborts instead of being silently dropped.
"""
import io, json, os, re, sys, tarfile, urllib.request

# Kotlin name -> Glyphs icon (the "-bold" variants are solid shapes and read best at toolbar size)
ICONS = {
    "PENCIL": "pencil-bold", "ERASER": "strikethrough-bold", "SELECT": "object-select-bold", "HAND": "hand-bold",
    "UNDO": "arrow-turn-bold", "TRASH": "trash-bold", "PLUS": "plus-bold", "SAVE": "save-bold", "THEME": "circle-half-bold",
    "SETTINGS": "cog-bold", "CHEVRON": "chevron-bold", "RECALCULATE": "repeat-bold", "EDIT": "edit-bold", "ZOOM_IN": "zoom-in-bold",
    "EYE": "eye-bold", "EYE_OFF": "eye-slash-bold", "FOLDER_OPEN": "folder-open-bold", "GRAPH": "chart-line-bold", "SHARE": "share-bold",
}

CAP = {"butt": "BUTT", "round": "ROUND", "square": "SQUARE"}
JOIN = {"miter": "MITER", "round": "ROUND", "bevel": "BEVEL"}

def parse(name, body):
    """Walks <g>/<path> tokens, applying group-level fill/stroke defaults to child paths. Aborts on anything unsupported."""
    if re.search(r"<(?!path\b|/path\b|g\b|/g\b)[a-z]", body):
        sys.exit(f"{name}: contains non-path elements")
    stack = [{}]
    paths = []
    for m in re.finditer(r"<(/?)(g|path)\b([^>]*?)(/?)>", body):
        closing, tag, raw, selfclose = m.groups()
        attrs = dict(re.findall(r'([\w-]+)="([^"]*)"', raw))
        bad = {k for k in attrs if k in ("opacity", "fill-opacity", "stroke-opacity", "transform", "style", "mask", "filter", "clip-path")}
        if bad:
            sys.exit(f"{name}: unsupported attributes {bad}")
        if tag == "g":
            if closing:
                stack.pop()
            else:
                stack.append({**stack[-1], **{k: v for k, v in attrs.items() if k != "d"}})
            continue
        eff = {**stack[-1], **attrs}
        fill = eff.get("fill", "currentColor") != "none"
        if eff.get("fill", "currentColor") not in ("currentColor", "none"):
            sys.exit(f"{name}: unsupported fill {eff['fill']}")
        stroke = eff.get("stroke")
        if stroke not in (None, "none", "currentColor"):
            sys.exit(f"{name}: unsupported stroke {stroke}")
        width = float(eff.get("stroke-width", 1)) if stroke == "currentColor" else 0.0
        cap = CAP[eff.get("stroke-linecap", "butt")]
        join = JOIN[eff.get("stroke-linejoin", "miter")]
        paths.append((attrs["d"], eff.get("fill-rule") == "evenodd", fill, width, cap, join))
    if not paths:
        sys.exit(f"{name}: no paths")
    return paths

def main(text):
    data = json.loads(text)
    w, h = float(data.get("width", 80)), float(data.get("height", 80))
    out = ['package com.bsoft.bhandbook.core.icons', '',
           '// GENERATED by scripts/generate_glyphs.py from the Iconify "Glyphs" set. Do not edit by hand.', '',
           'object Glyphs {',
           '    const val AUTHOR = "Goran Spasojevic (https://github.com/gorango/glyphs)"',
           '    const val LICENSE = "MIT"', '']
    for key, icon in ICONS.items():
        if icon not in data["icons"]:
            sys.exit(f"missing icon {icon}")
        ps = parse(icon, data["icons"][icon]["body"])
        items = ", ".join(
            f'GlyphPath("{d}", {str(eo).lower()}, {str(fl).lower()}, {w_}f, StrokeCapKind.{cap}, StrokeJoinKind.{join})' for d, eo, fl, w_, cap, join in ps)
        out.append(f'    val {key} = Glyph("{icon}", {w}f, {h}f, listOf({items}))')
    out += ['', '    val all: Map<String, Glyph> = mapOf(' + ", ".join(f'"{k}" to {k}' for k in ICONS) + ')', '}', '']
    open("app/src/main/java/com/bsoft/bhandbook/core/icons/GlyphData.kt", "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote", len(ICONS), "icons")

def fetch_icons_json():
    """Downloads the published @iconify-json/glyphs package and returns its icons.json text."""
    meta_url = "https://registry.npmjs.org/@iconify-json%2Fglyphs/latest"
    with urllib.request.urlopen(meta_url, timeout=60) as r:
        meta = json.load(r)
    print("downloading", meta["dist"]["tarball"], "(version", meta["version"] + ", licence", meta.get("license", "?") + ")")
    with urllib.request.urlopen(meta["dist"]["tarball"], timeout=120) as r:
        data = r.read()
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as t:
        return t.extractfile("package/icons.json").read().decode("utf-8")

if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    os.chdir(os.path.dirname(here))                          # always write relative to the project root, wherever it is run from
    if len(sys.argv) > 1:
        if not os.path.exists(sys.argv[1]):
            sys.exit(f"file not found: {sys.argv[1]}")
        text = open(sys.argv[1], encoding="utf-8").read()
    else:
        try:
            text = fetch_icons_json()
        except Exception as e:                               # noqa: BLE001
            sys.exit(f"could not download the icon package ({e}).\nDownload https://registry.npmjs.org/@iconify-json/glyphs/latest manually, extract package/icons.json and pass its path.")
    main(text)
